// ---------------------------------------------------------------- examples
const exDir = "docs/examples";
fs.mkdirSync(exDir, { recursive: true });
const index = [
  "# Example requests and responses",
  "",
  "One passing (and, where the run had one, one failing) exchange per endpoint, recorded by the API tests.",
  "",
  "| Endpoint | Example |",
  "|---|---|",
];
for (const ep of inventory.endpoints) {
  const cs = results.cases.filter((c) => c.endpointId === ep.id && c.evidence?.length);
  const good =
    cs.find((c) => c.status === "passed" && c.category === "success") ??
    cs.find((c) => c.status === "passed");
  const bad =
    cs.find((c) => c.status === "failed") ??
    cs.find((c) => c.status === "passed" && c !== good && c.evidence[0]?.status >= 400);
  const file = `${ep.id}.md`;
  const body = [`# ${ep.method} \`${ep.path}\``, "", ep.purpose, ""];
  for (const [label, c] of [
    ["Example", good],
    [bad?.status === "failed" ? "Failing case" : "Error example", bad],
  ]) {
    if (!c) continue;
    const ex = c.evidence[0];
    body.push(
      `## ${label}: ${c.title}`,
      "",
      `\`${ex.method} ${ex.url}\` → **HTTP ${ex.status}** in ${ms(ex.durationMs)}`,
      "",
    );
    if (ex.requestBody !== undefined)
      body.push("Request body:", "", "```json", json(ex.requestBody), "```", "");
    if (ex.responseHeaders && Object.keys(ex.responseHeaders).length)
      body.push(
        "Response headers:",
        "",
        "```text",
        Object.entries(ex.responseHeaders)
          .map(([k, v]) => `${k}: ${v}`)
          .join("\n"),
        "```",
        "",
      );
    body.push("Response body:", "", "```json", json(ex.responseBody ?? null).slice(0, 4000), "```", "");
    if (c.error) body.push("Failure:", "", "```text", c.error.slice(0, 1500), "```", "");
  }
  if (!good && !bad) body.push("_No recorded exchange in this run._");
  fs.writeFileSync(path.join(exDir, file), body.join("\n"));
  index.push(`| ${ep.method} \`${ep.path}\` | [${file}](${file}) |`);
}
const shotsFrom = "e2e-report/before-restart/screenshots";
if (fs.existsSync(shotsFrom)) {
  fs.mkdirSync(path.join(exDir, "screenshots"), { recursive: true });
  const shots = fs
    .readdirSync(shotsFrom)
    .filter((f) => f.endsWith(".png"))
    .sort();
  for (const f of shots) fs.copyFileSync(path.join(shotsFrom, f), path.join(exDir, "screenshots", f));
  index.push("", "## Screenshots", "", ...shots.map((f) => `- [${f}](screenshots/${f})`));
}
fs.writeFileSync(path.join(exDir, "README.md"), index.join("\n"));
console.log(
  `report: docs/api-test-report.md, test-results/report.html, ${inventory.endpoints.length} examples in docs/examples/`,
);

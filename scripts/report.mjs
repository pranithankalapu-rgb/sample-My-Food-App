// Writes the API test report from test-results/results.json (+ baseline.json):
//   docs/api-test-report.md      the report (Markdown)
//   test-results/report.html     the same report as a standalone HTML page
//   docs/examples/<endpoint>.md  example request/response pairs per endpoint
//   docs/examples/screenshots/   screenshots of every page (from the Playwright run)
import fs from "node:fs";
import path from "node:path";

const results = JSON.parse(fs.readFileSync("test-results/results.json", "utf8"));
const baseline = fs.existsSync("test-results/baseline.json")
  ? JSON.parse(fs.readFileSync("test-results/baseline.json", "utf8"))
  : null;
const inventory = JSON.parse(fs.readFileSync("src/data/api-inventory.json", "utf8"));
const comparable = baseline && baseline.runId !== results.runId ? baseline : null;

const ms = (v) =>
  v === null || v === undefined ? "—" : v >= 1000 ? `${(v / 1000).toFixed(2)} s` : `${Math.round(v)} ms`;
const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");
const json = (v) => (typeof v === "string" ? v : JSON.stringify(v, null, 2));
const s = results.summary;

const out = [];
out.push("# My Food App API: test report", "");
out.push(`${results.label} · run \`${results.runId}\` · ${results.startedAt} → ${results.finishedAt}`, "");
out.push(
  `Backend \`${results.backendCommit}\` · web app \`${results.frontendCommit}\` · generated by \`scripts/report.mjs\` from \`test-results/results.json\` (also shown on the Test Dashboard, http://localhost:4200/#/tests).`,
  "",
);

out.push("## Summary", "");
out.push("| | |", "|---|---|");
out.push(`| Test cases | **${s.total}**: ${s.passed} passed, **${s.failed} failed**, ${s.skipped} skipped |`);
out.push(`| Endpoints in the inventory | ${results.coverage.endpoints} |`);
out.push(
  `| Endpoints in the typed client and the API Explorer | ${results.coverage.integrated} of ${results.coverage.endpoints} (100%) |`,
);
out.push(
  `| Endpoints with API tests | ${results.coverage.tested} of ${results.coverage.endpoints}${results.coverage.untested.length ? ` (missing: ${results.coverage.untested.join(", ")})` : ""} |`,
);
const bySuite = {};
for (const c of results.cases) {
  bySuite[c.suite] ??= { passed: 0, failed: 0, skipped: 0 };
  bySuite[c.suite][c.status] += 1;
}
for (const [suite, v] of Object.entries(bySuite))
  out.push(
    `| ${suite} cases | ${v.passed} passed, ${v.failed} failed${v.skipped ? `, ${v.skipped} skipped` : ""} |`,
  );
out.push(`| Duration | ${ms(s.durationMs)} |`, "");
if (results.notes?.length) out.push(...results.notes.map((n) => `> ${n}`), "");

out.push("## Results per endpoint", "");
out.push("| Endpoint | Cases | Passed | Failed | Categories | p50 / p95 |", "|---|---|---|---|---|---|");
for (const ep of inventory.endpoints) {
  const cs = results.cases.filter((c) => c.endpointId === ep.id);
  const perf = results.perf.filter((p) => p.endpointId === ep.id);
  out.push(
    `| ${ep.method} \`${ep.path}\` | ${cs.length} | ${cs.filter((c) => c.status === "passed").length} | ${cs.filter((c) => c.status === "failed").length || ""} | ${cell([...new Set(cs.map((c) => c.category))].join(", "))} | ${perf.map((p) => `${ms(p.p50)} / ${ms(p.p95)}${p.flagged ? " ⚠" : ""}`).join("; ") || "—"} |`,
  );
}
out.push("");

const failures = results.cases.filter((c) => c.status === "failed");
out.push(`## Failures (${failures.length})`, "");
if (!failures.length) out.push("None.", "");
for (const c of failures) {
  out.push(`### ${c.suite} · ${c.endpointId ?? c.page ?? "-"} · ${c.title}`, "");
  if (c.error) out.push("```text", c.error.replace(/\u001b\[\d+m/g, "").slice(0, 1500), "```", "");
  for (const ex of c.evidence ?? []) {
    out.push(
      `**${ex.method} ${ex.url}** → HTTP ${ex.status} in ${ms(ex.durationMs)}${ex.error ? ` (${ex.error})` : ""}`,
      "",
    );
    if (ex.requestBody !== undefined) out.push("Request body:", "```json", json(ex.requestBody), "```");
    out.push("Response body:", "```json", json(ex.responseBody ?? null).slice(0, 1500), "```", "");
  }
}

out.push("## Speed (p50/p95 over 20 calls; AI paths fewer, see note)", "");
out.push("DB-only calls are flagged when p95 is over 500 ms, calls to an external service over 3 s.", "");
out.push(
  "| Call | Kind | Samples | p50 | p95 | Max | Budget | Errors | |",
  "|---|---|---|---|---|---|---|---|---|",
);
for (const p of results.perf)
  out.push(
    `| ${cell(p.label)}${p.note ? ` (${cell(p.note)})` : ""} | ${p.kind} | ${p.samples} | ${ms(p.p50)} | ${ms(p.p95)} | ${ms(p.max)} | ${ms(p.budgetMs)} | ${p.errors || ""} | ${p.flagged ? "⚠ slow" : ""} |`,
  );
out.push("");

out.push("## Accuracy against live Open Food Facts", "");
const checkedAcc = results.accuracy.filter((a) => !a.unchecked);
const okAcc = checkedAcc.filter((a) => a.ok).length;
const uncheckedAcc = results.accuracy.length - checkedAcc.length;
out.push(
  `${okAcc} of ${checkedAcc.length} checked products match Open Food Facts on every field (name, brand, 5 nutrients, ingredients, image)${uncheckedAcc ? `; ${uncheckedAcc} of ${results.accuracy.length} could not be checked because Open Food Facts did not answer (rate limit or outage), and they are not counted as matches or mismatches` : ""}.`,
  "",
);
if (results.accuracy.length) {
  out.push("| Product | Mismatches |", "|---|---|");
  for (const a of results.accuracy) {
    const bad = a.fields
      .filter((f) => !f.match)
      .map(
        (f) =>
          `**${f.field}**: API “${cell(f.api).slice(0, 80)}” vs OFF “${cell(f.reference).slice(0, 80)}”${f.note ? ` (${f.note})` : ""}`,
      );
    out.push(
      `| ${cell(a.name)} \`${a.code}\` | ${a.unchecked ? `not checked: ${cell(a.unchecked)}` : bad.join("<br>") || "—"} |`,
    );
  }
  out.push("");
}

out.push("## Ingredient lists", "");
const okIng = results.ingredients.filter((r) => r.ok).length;
out.push(`${okIng} of ${results.ingredients.length} ingredient lists have no problem.`, "");
if (results.ingredients.length) {
  out.push("| Product | Issues | Text (start) |", "|---|---|---|");
  for (const r of results.ingredients)
    out.push(
      `| ${cell(r.name)} \`${r.code}\` | ${cell(r.issues.join("; ")) || "—"} | ${cell(r.text.slice(0, 100))} |`,
    );
  out.push("");
}

out.push("## Fallback and outages", "");
out.push("| Case | Result |", "|---|---|");
for (const c of results.cases.filter((x) => x.suite === "fallback"))
  out.push(
    `| ${cell(c.title)} | ${c.status === "passed" ? "passed" : `**failed**: ${cell((c.error ?? "").split("\n")[0]).slice(0, 200)}`} |`,
  );
out.push("");

out.push("## Lighthouse", "");
out.push(
  "| Page | Preset | Performance | Accessibility | Best practices | SEO |",
  "|---|---|---|---|---|---|",
);
for (const l of results.lighthouse)
  out.push(
    `| ${l.page} | ${l.preset} | ${l.performance} | ${l.accessibility} | ${l.bestPractices} | ${l.seo ?? "—"} |`,
  );
out.push("");

if (comparable) {
  const before = new Map(comparable.cases.map((c) => [c.id, c]));
  const fixed = results.cases.filter((c) => c.status === "passed" && before.get(c.id)?.status === "failed");
  const broke = results.cases.filter((c) => c.status === "failed" && before.get(c.id)?.status === "passed");
  out.push("## Before / after", "");
  out.push(
    `Baseline: ${comparable.label} (\`${comparable.runId}\`, backend \`${comparable.backendCommit.slice(0, 7)}\`): ${comparable.summary.failed} failed of ${comparable.summary.total}. Now: ${s.failed} failed of ${s.total}.`,
    "",
  );
  out.push(`Fixed (${fixed.length}):`, ...fixed.map((c) => `- ${c.title}`), "");
  out.push(`Newly failing (${broke.length}):`, ...broke.map((c) => `- ${c.title}`), "");
  const perfBefore = new Map(comparable.perf.map((p) => [`${p.endpointId}|${p.label}`, p]));
  out.push("| Call | p95 before | p95 after |", "|---|---|---|");
  for (const p of results.perf) {
    const b = perfBefore.get(`${p.endpointId}|${p.label}`);
    if (b) out.push(`| ${cell(p.label)} | ${ms(b.p95)} | ${ms(p.p95)} |`);
  }
  const lhBefore = new Map(comparable.lighthouse.map((l) => [`${l.preset}|${l.page}`, l]));
  out.push("", "| Lighthouse | before (perf / a11y / bp) | after |", "|---|---|---|");
  for (const l of results.lighthouse) {
    const b = lhBefore.get(`${l.preset}|${l.page}`);
    if (b)
      out.push(
        `| ${l.preset} ${l.page} | ${b.performance} / ${b.accessibility} / ${b.bestPractices} | ${l.performance} / ${l.accessibility} / ${l.bestPractices} |`,
      );
  }
  out.push("");
}

out.push("## All cases", "");
out.push("| Suite | Endpoint / page | Category | Case | Result | Time |", "|---|---|---|---|---|---|");
for (const c of results.cases)
  out.push(
    `| ${c.suite} | ${c.endpointId ?? c.page ?? ""} | ${cell(c.category)} | ${cell(c.title)} | ${c.status === "failed" ? "**failed**" : c.status} | ${ms(c.durationMs)} |`,
  );
out.push("");

const md = out.join("\n");
fs.mkdirSync("docs", { recursive: true });
fs.writeFileSync("docs/api-test-report.md", md);

// ---------------------------------------------------------------- HTML
const esc = (t) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function inline(t) {
  return esc(t)
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/&lt;br&gt;/g, "<br>");
}
function toHtml(markdown) {
  const lines = markdown.split("\n");
  const html = [];
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (line.startsWith("```")) {
      const block = [];
      for (i += 1; i < lines.length && !lines[i].startsWith("```"); i += 1) block.push(lines[i]);
      html.push(`<pre>${esc(block.join("\n"))}</pre>`);
    } else if (/^#{1,3} /.test(line)) {
      const level = line.indexOf(" ");
      html.push(`<h${level}>${inline(line.slice(level + 1))}</h${level}>`);
    } else if (line.startsWith("|")) {
      const rows = [];
      for (; i < lines.length && lines[i].startsWith("|"); i += 1) rows.push(lines[i]);
      i -= 1;
      const split = (r) =>
        r
          .slice(1, -1)
          .split(/(?<!\\)\|/)
          .map((c) => c.trim().replace(/\\\|/g, "|"));
      const [head, , ...body] = rows;
      html.push(
        `<div class="table"><table><thead><tr>${split(head)
          .map((c) => `<th>${inline(c)}</th>`)
          .join("")}</tr></thead><tbody>${body
          .map(
            (r) =>
              `<tr>${split(r)
                .map((c) => `<td>${inline(c)}</td>`)
                .join("")}</tr>`,
          )
          .join("")}</tbody></table></div>`,
      );
    } else if (line.startsWith("- ")) {
      const items = [];
      for (; i < lines.length && lines[i].startsWith("- "); i += 1)
        items.push(`<li>${inline(lines[i].slice(2))}</li>`);
      i -= 1;
      html.push(`<ul>${items.join("")}</ul>`);
    } else if (line.startsWith("> ")) {
      html.push(`<blockquote>${inline(line.slice(2))}</blockquote>`);
    } else if (line.trim()) {
      html.push(`<p>${inline(line)}</p>`);
    }
  }
  return html.join("\n");
}
